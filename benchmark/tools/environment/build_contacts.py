"""Prepare portable sand contact samples and an analytic soft dust mask.
Audio derives from Fantozzi's CC0 recordings; source files are preserved.
Run with Python 3 and FFmpeg. This does not generate character voice recordings.
"""
from pathlib import Path
import hashlib,json,math,shutil,struct,subprocess,zlib

ROOT=Path(__file__).resolve().parents[3]
SOURCE=ROOT/'benchmark/art/audio/fantozzi'
OUT=ROOT/'benchmark/shared/audio'
FX=ROOT/'benchmark/shared/effects'
OUT.mkdir(parents=True,exist_ok=True);FX.mkdir(parents=True,exist_ok=True)
ffmpeg=shutil.which('ffmpeg')
if not ffmpeg:raise RuntimeError('FFmpeg is required for the preserved contact audio recipe')
inputs=sorted((SOURCE/'source/Fantozzi-footsteps/flac').glob('*Sand*.flac'))
if len(inputs)!=6:raise RuntimeError('Expected the six original CC0 sand contact recordings')
recipes={
    'Krag':'asetrate=37485,aresample=48000,highpass=f=45,bass=g=6:f=110:w=0.8,alimiter=limit=0.8:level=false,volume=0.85',
    'Nib':'asetrate=45423,aresample=48000,highpass=f=160,alimiter=limit=0.8:level=false,volume=0.42',
}
manifest={'schemaVersion':1,'status':'Contact presentation candidates; in-engine synchronization and listening review pending','species':{},'source':{
    'title':"Fantozzi's Footsteps (Grass/Sand & Stone)",'author':'Fantozzi','editingContributor':'qubodup',
    'assetPage':'https://opengameart.org/content/fantozzis-footsteps-grasssand-stone',
    'download':'https://opengameart.org/sites/default/files/Fantozzi-footsteps.7z',
    'license':'CC0','licenseUrl':'https://creativecommons.org/publicdomain/zero/1.0/',
    'archiveSha256':hashlib.sha256((SOURCE/'Fantozzi-footsteps.7z').read_bytes()).hexdigest(),
    'inputFiles':[{'name':p.name,'sha256':hashlib.sha256(p.read_bytes()).hexdigest()} for p in inputs],
}}
for species,recipe in recipes.items():
    files=[]
    for index,source in enumerate(inputs,1):
        path=OUT/f'{species}_Sand_{index:02}.wav'
        subprocess.run([ffmpeg,'-hide_banner','-loglevel','error','-y','-i',str(source),'-af',recipe,'-ac','1','-ar','48000','-c:a','pcm_s16le',str(path)],check=True)
        files.append(path.name)
    manifest['species'][species]={'sandSteps':files,'filterRecipe':recipe,'runtimeGain':1.0,'runtimePitchVariation':[.97,1.03]}
(OUT/'manifest.json').write_text(json.dumps(manifest,indent=2)+'\n')
(SOURCE/'source.json').write_text(json.dumps(manifest['source'],indent=2)+'\n')

# A mathematical alpha field, not a painted scene or a baked lighting texture.
# White RGB lets the engine shade/tint the same mask under its own desert light.
size=128
rows=bytearray()
for y in range(size):
    rows.append(0)
    for x in range(size):
        u=(x+.5)/size*2-1;v=(y+.5)/size*2-1
        radius=math.sqrt(u*u+v*v)
        variation=.84+.09*math.sin(8*u+3*v)+.07*math.sin(5*v-7*u)
        edge=max(0,min(1,(1-radius)/.25))
        alpha=round(255*math.exp(-3.8*radius*radius)*edge*variation)
        rows.extend((255,255,255,max(0,min(255,alpha))))
def chunk(tag,data):return struct.pack('>I',len(data))+tag+data+struct.pack('>I',zlib.crc32(tag+data)&0xffffffff)
png=b'\x89PNG\r\n\x1a\n'+chunk(b'IHDR',struct.pack('>IIBBBBB',size,size,8,6,0,0,0))+chunk(b'IDAT',zlib.compress(rows,9))+chunk(b'IEND',b'')
(FX/'SandDustMask.png').write_bytes(png)
(FX/'manifest.json').write_text(json.dumps({'schemaVersion':1,'dustMask':'SandDustMask.png','authoring':'Analytic soft radial alpha field generated by benchmark/tools/environment/build_contacts.py','use':'Engine-lit transient sand-contact particles; stronger Krag and lighter Nib emission.','status':'Runtime visual review pending'},indent=2)+'\n')
print('CONTACT_ASSETS_READY',len(inputs)*len(recipes),'WAV files and shared dust mask')
